import path from "node:path";
import { fileURLToPath } from "node:url";
import YAML from "yaml";
import { computePageFingerprint, normalizeEol } from "./handbook-lib.mjs";

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const repoPath = (...segments) => path.join(REPO_ROOT, ...segments);

const NON_CLAIMS = {
  en: [
    "This page is generated reference material; it asserts no Gate, release, Profile, or benefit result.",
    "Presence of a surface here is not a support or stability promise beyond the linked sources.",
  ],
  "zh-CN": [
    "本页为生成的参考资料，不构成任何 Gate、release、Profile 或收益结论。",
    "此处列出的接口面不构成超出所链接源码的支持或稳定性承诺。",
  ],
};

const GENERATED_MARKER =
  "<!-- @generated by tools/src/generate-handbook.mjs — DO NOT EDIT; edit sources/annotations and regenerate. -->";

function yamlList(items, indent) {
  return items.map((item) => `${indent}- ${JSON.stringify(item)}`).join("\n");
}

function frontmatter({ docId, locale, audience, sources, fingerprint }) {
  const lines = [
    "---",
    `doc_id: ${docId}`,
    `locale: ${locale}`,
    "kind: reference",
    `audience: [${audience.join(", ")}]`,
    "status: implemented",
    "generated: true",
    "sources:",
    ...sources.map((s) => `  - path: ${s}`),
    `fingerprint: "${fingerprint}"`,
    "non_claims:",
    yamlList(NON_CLAIMS[locale], "  "),
    "---",
    "",
    GENERATED_MARKER,
    "",
  ];
  return lines.join("\n");
}

function assertBidirectional(extracted, annotated, family) {
  const extractedSet = new Set(extracted);
  const annotatedSet = new Set(annotated);
  const missingAnnotation = [...extractedSet].filter((v) => !annotatedSet.has(v)).sort();
  const staleAnnotation = [...annotatedSet].filter((v) => !extractedSet.has(v)).sort();
  if (missingAnnotation.length > 0 || staleAnnotation.length > 0) {
    throw new Error(
      `${family}: annotation drift — extracted-without-annotation: [${missingAnnotation.join(", ")}]; annotated-without-literal: [${staleAnnotation.join(", ")}]`,
    );
  }
}

