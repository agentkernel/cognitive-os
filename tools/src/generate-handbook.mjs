/**
 * Build every generated page. Returns Map<repoPath, fullFileText>.
 * `readSource(repoPath)` must return tracked file text; `trackedPaths` is the
 * repo `git ls-files` list (needed by schema/env enumeration).
 */
export function buildGeneratedPages({ readSource, manifest, trackedPaths = [] }) {
  const output = new Map();
  const localeRoots = manifest.locale_roots ?? { en: "personal/handbook/en", "zh-CN": "personal/handbook/zh-CN" };
  for (const doc of manifest.documents ?? []) {
    if (!doc.generated) continue;
    const builder = FAMILY_BUILDERS[doc.doc_id];
    if (!builder) {
      throw new Error(`no generator registered for generated document ${doc.doc_id}`);
    }
    const { sources, bodies } = builder(readSource, trackedPaths);
    const fingerprintSources = [...new Set(sources)].sort();
    const fingerprint = computePageFingerprint(fingerprintSources, readSource);
    for (const locale of manifest.locales ?? ["en", "zh-CN"]) {
      const filePath = `${localeRoots[locale]}/${doc.rel_path}`;
      const head = frontmatter({ docId: doc.doc_id, locale, audience: doc.audience, sources: fingerprintSources, fingerprint });
      output.set(filePath, `${head}${bodies[locale]}`);
    }
  }
  return output;
}

function main() {
  const check = process.argv.includes("--check");
  const readSource = (rel) => readFileSync(repoPath(...rel.split("/")), "utf8");
  const manifest = JSON.parse(readSource("personal/handbook/_meta/manifest.json"));
  const trackedPaths = execFileSync("git", ["-C", REPO_ROOT, "ls-files"], { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 })
    .split("\n")
    .filter(Boolean);
  const pages = buildGeneratedPages({ readSource, manifest, trackedPaths });
  let drift = 0;
  for (const [filePath, content] of pages) {
    const absolute = repoPath(...filePath.split("/"));
    if (check) {
      let current = null;
      try {
        current = normalizeEol(readFileSync(absolute, "utf8"));
      } catch {
        current = null;
      }
      if (current !== content) {
        console.error(`generate-handbook --check: drift in ${filePath}`);
        drift += 1;
      }
    } else {
      mkdirSync(path.dirname(absolute), { recursive: true });
      writeFileSync(absolute, content, "utf8");
      console.log(`generated ${filePath}`);
    }
  }
  if (check) {
    if (drift > 0) {
      console.error(`generate-handbook --check: ${drift} generated page(s) drifted; run the generator`);
      process.exit(1);
    }
    console.log(`generate-handbook --check: OK (${pages.size} pages byte-identical)`);
  }
}

const invokedDirectly = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  main();
}
