function extractRustStringConst(text, constName) {
  const marker = `${constName}: &str = "`;
  const start = text.indexOf(marker);
  if (start === -1) throw new Error(`const ${constName} not found`);
  const from = start + marker.length;
  const end = text.indexOf('";', from);
  if (end === -1) throw new Error(`const ${constName} is unterminated`);
  return text
    .slice(from, end)
    .replaceAll("\\n", "\n")
    .replaceAll('\\"', '"')
    .replaceAll("\\\\", "\\");
}

